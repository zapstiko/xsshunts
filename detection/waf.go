// WAFInfo describes a detected WAF / rate limiter.
type WAFInfo struct {
	Name   string
	Type   string
	Status int
	Reason string
}

// DetectWAF inspects status, headers, and body for WAF / rate-limit fingerprints.
func DetectWAF(statusCode int, headers map[string]string, body string) *WAFInfo {
	headersLower := map[string]string{}
	for k, v := range headers {
		headersLower[strings.ToLower(k)] = strings.ToLower(v)
	}
	bodyLower := strings.ToLower(body)

	if statusCode == 429 || strings.Contains(bodyLower, "too many requests") || strings.Contains(bodyLower, "rate limit exceeded") {
		return &WAFInfo{Name: "Rate-Limiter", Type: "Rate-Limit", Status: statusCode, Reason: "HTTP 429 / Rate Limit Exceeded"}
	}

	serverVal := headersLower["server"]

	for _, sig := range WAFSignatures {
		for _, h := range sig.Headers {
			if _, ok := headersLower[h]; ok {
				return &WAFInfo{Name: sig.Name, Type: "WAF", Status: statusCode, Reason: fmt.Sprintf("Header '%s' detected", h)}
			}
		}
		for _, s := range sig.Server {
			if strings.Contains(serverVal, s) {
				return &WAFInfo{Name: sig.Name, Type: "WAF", Status: statusCode, Reason: fmt.Sprintf("Server header '%s'", serverVal)}
			}
		}
		for _, b := range sig.Body {
			if strings.Contains(bodyLower, b) {
				return &WAFInfo{Name: sig.Name, Type: "WAF", Status: statusCode, Reason: fmt.Sprintf("Signature '%s' in body", b)}
			}
		}
	}

	if statusCode == 403 {
		for _, g := range []string{"access denied", "request blocked", "forbidden", "web application firewall", "security rule"} {
			if strings.Contains(bodyLower, g) {
				return &WAFInfo{Name: "Generic WAF", Type: "WAF", Status: statusCode, Reason: fmt.Sprintf("HTTP 403 with '%s' in body", g)}
			}
		}
	}
	return nil
}

// WAFManager tracks fingerprints and auto-throttles the scan.
type WAFManager struct {
	mu                sync.Mutex
	logger            *logger.Logger
	detectedWAF       string
	consecutiveBlocks int
	throttled         bool
	warned            bool
}

// NewWAFManager creates a WAF manager bound to a logger.
func NewWAFManager(log *logger.Logger) *WAFManager {
	return &WAFManager{logger: log}
}

// HandleResponse inspects one response and applies backoff when a WAF is hit.
func (m *WAFManager) HandleResponse(statusCode int, headers map[string]string, body string, cfg *models.ScanConfig) bool {
	wafInfo := DetectWAF(statusCode, headers, body)
	if wafInfo == nil {
		m.mu.Lock()
		m.consecutiveBlocks = 0
		m.mu.Unlock()
		return false
	}

	m.mu.Lock()
	m.consecutiveBlocks++
	wafName := wafInfo.Name

	if !m.warned || m.detectedWAF != wafName {
		m.detectedWAF = wafName
		m.warned = true
		if m.logger != nil {
			m.logger.Warning(fmt.Sprintf("WAF / Rate-Limit detected [%s] (%s)!", wafName, wafInfo.Reason))
		}
	}

	if cfg != nil && (!m.throttled || m.consecutiveBlocks >= 2) {
		m.throttled = true
		oldMin, oldMax, newMin, newMax := cfg.DoubleDelays()
		backoffSec := 2 + m.consecutiveBlocks
		if backoffSec > 8 {
			backoffSec = 8
		}
		if m.logger != nil {
			m.logger.Warning(fmt.Sprintf("auto-throttling active: increased delay (%d-%dms -> %d-%dms), backing off %ds...",
				oldMin, oldMax, newMin, newMax, backoffSec))
		}
		m.mu.Unlock()
		time.Sleep(time.Duration(backoffSec) * time.Second)
		return true
	}
	if cfg == nil && m.consecutiveBlocks >= 1 {
		m.mu.Unlock()
		time.Sleep(2 * time.Second)
		return true
	}
	m.mu.Unlock()
	return true
}
