// Package detection fingerprints WAFs and rate-limit responses.
package detection

import (
	"net/http"
	"strings"
)

type signature struct {
	Name    string
	Hints   []string // matched against "header: value" pairs and the lowercased body
}

var signatures = []signature{
	{Name: "cloudflare", Hints: []string{"cf-ray", "server:cloudflare", "cloudflare-nginx", "attention required", "checking your browser", "cdn-cgi/challenge", "www.cloudflare.com"}},
	{Name: "aws-waf", Hints: []string{"the request could not be satisfied", "awswaf", "awselb", "x-amzn-requestid"}},
	{Name: "akamai", Hints: []string{"akamai", "akamaighost", "reference #"}},
	{Name: "imperva", Hints: []string{"x-iinfo", "incapsula", "imperva"}},
	{Name: "modsecurity", Hints: []string{"mod_security", "modsecurity", "not acceptable!you have requested"}},
	{Name: "wordfence", Hints: []string{"generated by wordfence", "wordfence block"}},
	{Name: "f5-big-ip", Hints: []string{"the requested url was rejected", "as#session:"}},
	{Name: "sucuri", Hints: []string{"sucuri", "cloudproxy"}},
	{Name: "imunify360", Hints: []string{"imunify360", "imunify"}},
	{Name: "wallarm", Hints: []string{"wallarm"}},
	{Name: "openappsec", Hints: []string{"openappsec", "appsec"}},
	{Name: "naxsi", Hints: []string{"x-naxsi-signature", "naxsi caught"}},
}

// Detect returns the names of WAFs whose fingerprints appear in the response.
func Detect(h http.Header, body string) []string {
	if h == nil {
		return nil
	}
	hay := strings.ToLower(h.Get("Server") + " " + h.Get("X-Powered-By") + " " + h.Get("X-CDN") + " " + h.Get("X-CDN-Detail") + " " + h.Get("X-Backend-Server") + " " + h.Get("X-Sucuri-ID") + " " + h.Get("Set-Cookie") + " " + strings.ToLower(body))
	upper := h.Get("cf-ray") != "" || h.Get("x-iinfo") != "" || h.Get("x-ar-trace-id") != ""

	var found []string
	for _, sig := range signatures {
		for _, hint := range sig.Hints {
			if strings.Contains(hay, strings.ToLower(hint)) {
				found = append(found, sig.Name)
				break
			}
		}
	}
	if upper {
		if h.Get("cf-ray") != "" {
			found = append(found, "cloudflare")
		}
		if h.Get("x-iinfo") != "" {
			found = append(found, "imperva")
		}
	}
	return dedupe(found)
}

// IsRateLimited reports whether a response looks like rate limiting.
func IsRateLimited(status int, h http.Header) bool {
	if status == http.StatusTooManyRequests {
		return true
	}
	if status == http.StatusServiceUnavailable && strings.Contains(strings.ToLower(h.Get("Body")), "waf") {
		return true
	}
	return false
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range in {
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out
}
